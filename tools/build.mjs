/*
 * Build `index.html`: the whole instrument in one file, no imports, no origin.
 *
 * Several ways of opening this project cannot fetch `src/*.js`. `file://`
 * refuses module imports outright, and a preview pane that injects markup into a
 * sandboxed opaque origin -- an iframe with a srcdoc, a WebView -- has the same
 * trouble with no base URL to resolve against. Both would paint the CSS panels
 * over an empty canvas and never start the app, which reads as a broken toy
 * rather than a blocked request. An inline script needs no origin at all.
 *
 * So `index.html` -- the file to open, and the file Pages serves -- is generated
 * here from `src/page.html` plus a bundle of `src/*.js`. There is one entry
 * point and it works everywhere, rather than a page that works over a server
 * plus a second page that works anywhere. `tests/app.test.mjs` rebuilds and
 * compares bytes, so the generated file cannot drift from its sources.
 *
 *   node tools/build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadOptional } from './optional-deps.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = 'src/page.html';
const OUTPUT = 'index.html';
const ENTRY = 'src/app.js';
// The specifier the emitted page would need if it loaded a module at all, which
// is the tag this build replaces. Read from the project root rather than src/ so
// it matches what a browser would have to resolve.
const SCRIPT_TAG = '<script type="module" src="src/app.js"></script>';

/*
 * The template's comment describes the build that produces the root page. Both
 * comments are matched exactly, so editing the one in src/page.html fails the
 * build loudly rather than leaving a generated file that describes itself wrongly.
 */
const SOURCE_NOTE = '<!--\n  The markup, not the page. Everything in this file is hand-written; the\n  `index.html` at the root is generated from it plus a bundle of `src/*.js`, so\n  that one file opens anywhere. Edit this and run `node tools/build.mjs`.\n-->';
const STANDALONE_NOTE = '<!--\n  Generated from src/page.html + src/*.js by tools/build.mjs. One file,\n  nothing fetched: it opens from disk, from a sandboxed preview pane, or from\n  any static server. To change it, edit src/ and re-run that build.\n-->';

const banner =
  'Generated by tools/build.mjs from src/page.html + src/*.js.\n' +
  'Edit those and re-run the build; nothing here is hand-written.';

function bundle() {
  const esbuild = loadOptional('esbuild');
  if (esbuild === null) {
    throw new Error('esbuild is not available; run inside `nix develop --command`');
  }
  const result = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: [ENTRY],
    bundle: true,
    // A classic IIFE rather than a module: the whole point is to survive
    // contexts where module scripts cannot fetch anything.
    format: 'iife',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    write: false,
  });
  const js = result.outputFiles[0].text;
  // An inline script ends at the first `</script>` it sees, wherever that is.
  return js.replaceAll('</script', '<\\/script');
}

export function renderStandalone() {
  const page = readFileSync(path.join(root, TEMPLATE), 'utf8');
  if (!page.includes(SCRIPT_TAG)) {
    throw new Error(
      `${TEMPLATE} no longer contains ${SCRIPT_TAG}, which this build replaces`,
    );
  }
  for (const marker of [SCRIPT_TAG, SOURCE_NOTE]) {
    if (!page.includes(marker)) {
      throw new Error(`${TEMPLATE} no longer contains ${marker.slice(0, 40)}..., which this build replaces`);
    }
  }
  return page
    .replace('<!doctype html>', `<!doctype html>\n<!-- ${banner} -->`)
    .replace(SOURCE_NOTE, STANDALONE_NOTE)
    .replace(SCRIPT_TAG, `<script>${bundle()}</script>`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  // An explicit output path, so the build can be run where the source is read-only:
  // inside a Nix build the source tree lives in the store and writing index.html
  // there fails with EACCES. Defaults to the project root, which is what a
  // developer wants.
  const target = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, OUTPUT);
  const html = renderStandalone();
  writeFileSync(target, html);
  console.log(`${path.relative(root, target) || target}: ${(html.length / 1024).toFixed(1)} KB`);
}
